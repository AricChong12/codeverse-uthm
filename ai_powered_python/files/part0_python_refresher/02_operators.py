# Operators You'll See Everywhere

# Arithmetic operators are used to perform calculations.
total = 10 + 5
print(total) # 15
# % gives us the remainder after division.
print(10 % 3)
# -> 1


# == checks whether two values are equal.
# The result is either True or False.
print(5 == 5)
# -> True

# Comparison operators include <, <=, >, >=, and ==.
print(3 <= 10)
# -> True


# += adds a value to the existing variable.
# This is the same as: total = total + 1
total += 1 # total = total + 1
print(total)
# -> 16


# % is useful for checking whether a number is even.
# An even number has a remainder of 0 when divided by 2.
if 8 % 2 == 0:
    print("even!")
# -> even!

