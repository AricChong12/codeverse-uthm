# Variables, Types & Printing

# A variable stores a value that we can use later.
name = "Zulkifli"          # str = text
age = 21                   # int = whole number
price = 4.90               # float = decimal number
is_student = True          # bool = True or False

# print() displays values on the screen.
print(name, age)
# -> Zulkifli 21


# An f-string lets us insert variables directly into a string.
# Put the variable or expression inside { }.
print(f"{name} is {age} years old")
# -> Zulkifli is 21 years old